// Embeds the audit README and reproduction scripts into the engine so every
// audit bundle carries them. Run: node scripts/embed-audit.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = {
  "README.md": "audit/README.md",
  "audit/reproduce.py": "audit/reproduce.py",
  "audit/reproduce.R": "audit/reproduce.R",
  "audit/reproduce.sps": "audit/reproduce.sps",
};
const out = Object.fromEntries(Object.entries(files).map(([k, v]) => [k, readFileSync(join(root, v), "utf8")]));
writeFileSync(
  join(root, "src/lib/analysis/audit-scripts.generated.ts"),
  "// GENERATED by scripts/embed-audit.mjs from the audit/ folder. Do not edit.\n" +
    `export const AUDIT_SCRIPTS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log("embedded", Object.keys(out).length, "audit files");
