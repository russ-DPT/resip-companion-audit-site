// A working replica of the ReSIP Analysis page, driven by simulated data.
import { ANALYSIS_PLAN } from "@/src/lib/analysis/plan";
import { demoQuery, parseDemoParams } from "@/lib/site/demo-params";

export const metadata = { title: "Demo" };

export default async function DemoPage(props: { searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  const sp = await props.searchParams;
  const p = parseDemoParams((k) => (Array.isArray(sp[k]) ? sp[k]?.[0] : (sp[k] as string | undefined)));
  const q = demoQuery(p);
  const api = `/api/demo?${q}`;
  const isRA = p.role === "research_advisor";

  return (
    <>
      <h1>Demo: the study team&apos;s Analysis page</h1>
      <p className="banner">SIMULATED DATA. Every participant on this page is generated by the software. No real person is described.</p>
      <p>
        This is how the Analysis page will look inside the study platform. It runs the same locked analysis (plan {ANALYSIS_PLAN.id} v
        {ANALYSIS_PLAN.version}) on a simulated study. Change the settings to see how the report responds, including what each role
        sees and what happens while data collection is still open.
      </p>

      <form className="demo" method="get" action="/demo">
        <label>Simulated participants
          <input type="number" name="participants" min={6} max={40} defaultValue={p.participants} />
        </label>
        <label>Average change at T2 (points)
          <input type="number" name="effect" min={-20} max={10} defaultValue={p.effect} />
        </label>
        <label>Random seed
          <input type="number" name="seed" min={1} max={999999} defaultValue={p.seed} />
        </label>
        <label>View as
          <select name="role" defaultValue={p.role}>
            <option value="research_advisor">Research Advisor (faculty advisor)</option>
            <option value="principal_investigator">Principal Investigator</option>
          </select>
        </label>
        <label>Data collection
          <select name="status" defaultValue={p.status}>
            <option value="closed">Closed (all participants finished)</option>
            <option value="open">Still open (participants active)</option>
          </select>
        </label>
        <button type="submit">Run analysis</button>
      </form>

      {p.status === "open" ? (
        <div className="lock" role="status">
          <strong>Locked.</strong> Analysis is locked until data collection closes. 3 participant(s) are still active. On the real
          platform the investigator cannot see any outcome results until every participant has finished. (In this demo, switch
          &quot;Data collection&quot; to Closed to see the report.)
        </div>
      ) : (
        <>
          <div className="links">
            <a href={`${api}&format=html&download=1`}>Download report (HTML)</a>
            <a href={`${api}&format=csv`}>Download results (CSV)</a>
            <a href={`${api}&format=json`}>Download results (JSON)</a>
            {isRA ? <a href={`${api}&format=bundle`}>Download audit bundle (.zip)</a> : <span className="small">Audit bundle: Research Advisor only</span>}
          </div>
          {!isRA && <p className="small">Counts from 1 to 4 are shown as &lt;5 for this role.</p>}
          <iframe className="report" title="Analysis report (simulated)" src={`${api}&format=html`} sandbox="allow-same-origin" />
          <h2>Try the audit</h2>
          <ol>
            <li>Download the audit bundle (as the Research Advisor).</li>
            <li>Open <a href="/verify">Verify a bundle</a> and choose the file. Every check should pass.</li>
            <li>Unzip it and run <code>python3 audit/reproduce.py</code> or <code>Rscript audit/reproduce.R</code>; see the <a href="/audit">audit instructions</a>.</li>
          </ol>
        </>
      )}
    </>
  );
}
